// Bundle drizzle/*.sql into a TS module so the browser build can migrate without a filesystem.
import { readFileSync, writeFileSync } from "node:fs";
const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));
const list = journal.entries.map((e) => ({ tag: e.tag, sql: readFileSync(`drizzle/${e.tag}.sql`, "utf8") }));
writeFileSync(
  "src/lib/db/migrations.generated.ts",
  `// Generated by scripts/gen-web-migrations.mjs from drizzle/ — do not edit.\nexport const MIGRATIONS: Array<{ tag: string; sql: string }> = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`Bundled ${list.length} migration(s).`);
